<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

class ProductSeeder extends Seeder
{
    public function run(): void
    {
        $now = now();

        $sellers = DB::table('sellers')->where('status', 'active')->pluck('id')->toArray();
        if (empty($sellers)) {
            $this->command->warn('⚠️ No active sellers found. Run SellerSeeder first.');
            return;
        }

        $brandMap    = DB::table('brands')->pluck('id', 'slug')->toArray();
        $categoryMap = DB::table('categories')->pluck('id', 'slug')->toArray();

        $sellerMap = [
            0 => $sellers[0],
            1 => $sellers[1] ?? $sellers[0],
            2 => $sellers[2] ?? $sellers[0],
            3 => $sellers[3] ?? $sellers[0],
            4 => $sellers[4] ?? $sellers[0],
        ];

        $products = $this->getProductData();
        $seeded   = 0;

        foreach ($products as $p) {
            $categoryId = $categoryMap[$p['cat_slug']] ?? null;
            $brandId    = $p['brand'] ? ($brandMap[$p['brand']] ?? null) : null;
            $sellerId   = $sellerMap[$p['seller']];

            if (!$categoryId) {
                $this->command->warn("⚠️  Category slug '{$p['cat_slug']}' not found for product '{$p['name']}'. Skipping.");
                continue;
            }

            if (DB::table('products')->where('slug', $p['slug_key'])->exists()) {
                continue;
            }

            $productId = DB::table('products')->insertGetId([
                'seller_id'           => $sellerId,
                'category_id'         => $categoryId,
                'brand_id'            => $brandId,
                'name'                => $p['name'],
                'name_bn'             => $p['name_bn'],
                'slug'                => $p['slug_key'],
                'sku'                 => strtoupper(Str::random(3)) . '-' . rand(10000, 99999),
                'short_description'   => $p['excerpt'],
                'description'         => '<p>' . $p['excerpt'] . '</p>',
                'description_bn'      => '<p>' . $p['name_bn'] . '</p>',
                'price'               => $p['price'],
                'compare_price'       => $p['compare'],
                'cost_price'          => $p['cost'],
                'quantity'            => $p['qty'],
                'low_stock_threshold' => max(5, (int) ($p['qty'] * 0.1)),
                'weight'              => round(rand(1, 30) / 10, 1),
                'unit'                => 'piece',
                'has_variants'        => !empty($p['variants']),
                'is_active'           => true,
                'is_featured'         => $p['featured'],
                'is_new'              => $p['new'],
                'is_trending'         => $p['trending'],
                'free_shipping'       => $p['free_ship'],
                'total_views'         => rand(500, 20000),
                'tags'                => json_encode($p['tags']),
                'created_at'          => $now,
                'updated_at'          => $now,
            ]);

            // Primary image
            DB::table('product_images')->insert([
                'product_id' => $productId,
                'image_path' => $p['primary'],
                'sort_order' => 1,
                'is_primary' => true,
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            // Gallery images
            foreach ($p['gallery'] as $i => $url) {
                DB::table('product_images')->insert([
                    'product_id' => $productId,
                    'image_path' => $url,
                    'sort_order' => $i + 2,
                    'is_primary' => false,
                    'created_at' => $now,
                    'updated_at' => $now,
                ]);
            }

            // Variants
            foreach ($p['variants'] as $i => $variant) {
                [$attrName, $attrValue] = $variant;
                DB::table('product_variants')->insert([
                    'product_id'       => $productId,
                    'sku'              => 'V-' . $productId . '-' . ($i + 1),
                    'price'            => $p['price'] + ($i * 30),
                    'compare_price'    => $p['compare'] ? $p['compare'] + ($i * 30) : null,
                    'quantity'         => max(5, (int) ($p['qty'] / max(1, count($p['variants'])))),
                    'image'            => null,
                    'attribute_values' => json_encode([$attrName => $attrValue]),
                    'is_active'        => true,
                    'created_at'       => $now,
                    'updated_at'       => $now,
                ]);
            }

            $seeded++;
        }

        $this->command->info("✅ ProductSeeder: {$seeded} products seeded.");
        $this->command->info("   Total products: " . DB::table('products')->count());
    }

